// Builds dist/gp-ui.css (tokens + components + bundled fonts) and, with --styleguide, the
// standalone style guide at dist/styleguide/index.html. Tokens are read straight from
// src/tokens.ts (Node strips the types).
import { execFileSync } from 'node:child_process'
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { tokensCss } from '../src/css-vars.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dist = join(root, 'dist')
const require = createRequire(import.meta.url)
const args = new Set(process.argv.slice(2))

/** Latin + latin-ext faces from a Fontsource CSS file, renamed and pointed at dist/fonts. */
function fontFaces(pkg, cssFile, family) {
  const pkgDir = dirname(require.resolve(`${pkg}/package.json`))
  const css = readFileSync(join(pkgDir, cssFile), 'utf8')
  const out = []
  for (const m of css.matchAll(/\/\* ([\w-]+) \*\/\s*(@font-face \{[^}]+\})/g)) {
    const [, name, block] = m
    if (!/-latin-(ext-)?(wght|standard)-/.test(name)) continue
    const file = block.match(/url\(\.\/files\/([^)]+)\)/)[1]
    copyFileSync(join(pkgDir, 'files', file), join(dist, 'fonts', file))
    out.push(
      block
        .replace(/font-family: '[^']+'/, `font-family: '${family}'`)
        .replace(/url\(\.\/files\//, 'url(./fonts/'),
    )
  }
  return out.join('\n')
}

mkdirSync(join(dist, 'fonts'), { recursive: true })
const css = [
  '/* GP design system. Generated by packages/ui/scripts/build.mjs, do not edit. */',
  fontFaces('@fontsource-variable/inter', 'wght.css', 'Inter Variable'),
  fontFaces('@fontsource-variable/saira', 'standard.css', 'GP Display'),
  tokensCss(),
  readFileSync(join(root, 'src/components.css'), 'utf8'),
  readFileSync(join(root, 'src/broadcast.css'), 'utf8'),
].join('\n')
writeFileSync(join(dist, 'gp-ui.css'), css)
console.log(`@gp/ui: dist/gp-ui.css (${(css.length / 1024).toFixed(1)} KB)`)

if (args.has('--styleguide')) {
  const { build } = await import('esbuild')
  const out = join(dist, 'styleguide')
  mkdirSync(join(out, 'fonts'), { recursive: true })
  await build({
    entryPoints: [join(root, 'styleguide/main.ts')],
    outfile: join(out, 'styleguide.js'),
    bundle: true,
    format: 'iife',
    target: 'chrome120',
    logLevel: 'warning',
  })
  writeFileSync(join(out, 'gp-ui.css'), css)
  for (const f of readdirSync(join(dist, 'fonts'))) {
    copyFileSync(join(dist, 'fonts', f), join(out, 'fonts', f))
  }
  copyFileSync(join(root, 'styleguide/index.html'), join(out, 'index.html'))
  const page = join(out, 'index.html')
  console.log(`@gp/ui: style guide at ${page}`)
  if (args.has('--open') && process.platform === 'darwin') execFileSync('open', [page])
}
